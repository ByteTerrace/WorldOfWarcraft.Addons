test("RAID_CLASS_COLORS holds the client's classes with ColorMixin methods; C_ClassColor makes new ones", function()
    local h = Harness.new()
    local env = h.env
    local warrior = env.RAID_CLASS_COLORS.WARRIOR
    eq(warrior.colorStr, "ffc69b6d")
    eq(warrior.r, 198 / 255)
    local r, g, b = warrior:GetRGB()
    eq(g, 155 / 255)
    eq(b, 109 / 255)
    eq(select(4, warrior:GetRGBA()), 1)
    eq(warrior:GenerateHexColor(), "ffc69b6d")
    eq(warrior:GenerateHexColorNoAlpha(), "C69B6D")
    eq(warrior:GenerateHexColorMarkup(), "|cffc69b6d")
    eq(warrior:WrapTextInColorCode("Bob"), "|cffc69b6dBob|r")
    eq(table.concat({ warrior:GetRGBAsBytes() }, ","), "198,155,109")
    eq(env.RAID_CLASS_COLORS.SHAMAN.colorStr, "ff0070dd")
    eq(env.RAID_CLASS_COLORS.DEATHKNIGHT, nil, "a class the client doesn't have")
    local count = 0
    for _ in pairs(env.RAID_CLASS_COLORS) do count = count + 1 end
    eq(count, 9)
    throws(function() warrior:GetHSL() end, "GetHSL")
    local mage = env.C_ClassColor.GetClassColor("MAGE")
    truthy(mage:IsEqualTo(env.RAID_CLASS_COLORS.MAGE))
    truthy(mage ~= env.RAID_CLASS_COLORS.MAGE, "a new color each call")
    eq(select("#", env.C_ClassColor.GetClassColor("EVOKER")), 0)
    h:SetTarget({ name = "Hogger" })
    h:SetRestriction("Encounter", true)
    local wrapped = env.RAID_CLASS_COLORS.ROGUE:WrapTextInColorCode(env.UnitName("target"))
    truthy(env.issecretvalue(wrapped), "a secret name wraps into a secret string")
    eq(Reveal(wrapped), "|cfffff468Hogger|r")
    eq(env.C_ColorUtil.WrapTextInColorCode("x", "ff00ff00"), "|cff00ff00x|r")
end)
